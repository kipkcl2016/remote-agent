#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const packageJson = JSON.parse(readFileSync(join(projectRoot, "package.json"), "utf8"));
const version = packageJson.version;
if (typeof version !== "string" || !version) {
  throw new Error("package.json must define a non-empty version string");
}

const outPath = join(projectRoot, "src", "gateway-version.generated.ts");
const contents = `/** Generated by scripts/sync-gateway-version.mjs — do not edit. */
export const GATEWAY_VERSION = ${JSON.stringify(version)};
`;

writeFileSync(outPath, contents, "utf8");
